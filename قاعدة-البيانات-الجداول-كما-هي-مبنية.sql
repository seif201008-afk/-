-- ---------- دالة سلات التذكير (النسخة الحالية، 20 ساعة + احترام إعدادات المطعم) ----------
create or replace function public.due_carts()
 returns table(business_id uuid, page_id text, sender_id text, items_text text, page_token text)
 language sql
 security definer
 set search_path to 'public'
as $function$
  select c.business_id, c.page_id, c.sender_id, c.items_text, b.page_token
  from pending_carts c
  join businesses b on b.id = c.business_id
  where c.status = 'open'
    and c.items_text <> ''
    and c.updated_at < now() - interval '60 minutes'
    and c.updated_at > now() - interval '20 hours'
    and b.active
    and b.bot_enabled
    and b.cart_reminder_enabled
    and coalesce(b.is_open, true)
    and (
      b.open_time is null or b.close_time is null
      or (case
            when b.close_time > b.open_time
              then (now() at time zone 'Africa/Cairo')::time between b.open_time and b.close_time
            else (now() at time zone 'Africa/Cairo')::time >= b.open_time
              or (now() at time zone 'Africa/Cairo')::time < b.close_time
          end)
    )
    and not exists (
      select 1 from bot_pauses p
      where p.page_id = c.page_id and p.sender_id = c.sender_id
        and p.paused_at > now() - make_interval(mins => coalesce(b.human_pause_minutes, 60))
    )
    and not exists (
      select 1 from orders o
      where o.business_id = c.business_id and o.sender_id = c.sender_id
        and o.created_at > c.updated_at - interval '5 minutes'
    )
  limit 50;
$function$;

-- ---------- دالة الردود المعلّقة (لـ workflow "إرسال الردود") ----------
create or replace function public.pending_replies()
returns table(id bigint, business_id uuid, page_id text, sender_id text, text text, page_token text, last_msg timestamptz)
language sql
security definer
set search_path to 'public'
as $function$
  select r.id, r.business_id, r.page_id, r.sender_id, r.text, b.page_token,
         (select max(m.created_at) from message_log m where m.page_id = r.page_id and m.sender_id = r.sender_id) as last_msg
  from customer_replies r
  join businesses b on b.id = r.business_id
  where r.status = 'pending' and b.active
  order by r.id
  limit 20;
$function$;

-- ---------- قفل الدوال الداخلية عن المتصفح (إصلاح ثغرة تسريب page_token) ----------
revoke execute on function public.due_carts() from public, anon, authenticated;
revoke execute on function public.pending_replies() from public, anon, authenticated;
grant execute on function public.due_carts() to service_role;
grant execute on function public.pending_replies() to service_role;
