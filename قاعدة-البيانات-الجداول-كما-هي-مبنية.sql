-- ---------- أعمدة جديدة في businesses (إعدادات المطعم) ----------
alter table businesses add column if not exists feedback_enabled boolean not null default true;
alter table businesses add column if not exists feedback_delay_minutes integer not null default 180;
alter table businesses add column if not exists cart_reminder_enabled boolean not null default true;
alter table businesses add column if not exists bot_enabled boolean not null default true;

-- ---------- عمود جديد في unanswered_questions ----------
alter table unanswered_questions add column if not exists answered_by uuid;

-- ---------- جداول جديدة ----------
create table if not exists business_hours (
  id bigint generated by default as identity primary key,
  business_id uuid not null references businesses(id) on delete cascade,
  weekday smallint not null check (weekday between 0 and 6),
  is_closed boolean not null default false,
  open_time time,
  close_time time,
  sort_order int not null default 0
);
create index if not exists business_hours_biz_idx on business_hours (business_id, weekday, sort_order);

create table if not exists business_pauses (
  id bigint generated by default as identity primary key,
  business_id uuid not null references businesses(id) on delete cascade,
  scope text not null check (scope in ('orders','bot')),
  starts_at timestamptz not null default now(),
  ends_at timestamptz not null,
  reason text,
  canceled_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists business_pauses_biz_idx on business_pauses (business_id, ends_at);

create table if not exists faq_items (
  id bigint generated by default as identity primary key,
  business_id uuid not null references businesses(id) on delete cascade,
  question text not null,
  answer text not null,
  active boolean not null default true,
  sort_order int not null default 0,
  source text not null default 'manual' check (source in ('manual','customer_question')),
  source_question_id text,
  created_at timestamptz not null default now()
);
create index if not exists faq_items_biz_idx on faq_items (business_id, active, sort_order);

create table if not exists notifications (
  id bigint generated by default as identity primary key,
  business_id uuid not null references businesses(id) on delete cascade,
  type text not null,
  severity text not null default 'normal' check (severity in ('low','normal','high','urgent')),
  title text not null,
  body text,
  ref_table text,
  ref_id text,
  sender_id text,
  customer_name text,
  customer_phone text,
  requires_action boolean not null default false,
  reply_deadline timestamptz,
  status text not null default 'unread' check (status in ('unread','read','handled','dismissed')),
  created_at timestamptz not null default now(),
  read_at timestamptz,
  handled_at timestamptz
);
create index if not exists notifications_biz_idx on notifications (business_id, created_at desc);
create index if not exists notifications_unread_idx on notifications (business_id) where status = 'unread';

create table if not exists customer_replies (
  id bigint generated by default as identity primary key,
  business_id uuid not null references businesses(id) on delete cascade,
  page_id text not null,
  sender_id text not null,
  text text not null check (char_length(text) <= 1800),
  source_type text,
  source_id text,
  notification_id bigint references notifications(id) on delete set null,
  status text not null default 'pending' check (status in ('pending','sent','expired','failed')),
  sent_at timestamptz,
  error text,
  created_at timestamptz not null default now()
);
create index if not exists customer_replies_pending_idx on customer_replies (status) where status = 'pending';

create table if not exists notification_settings (
  id bigint generated by default as identity primary key,
  business_id uuid not null references businesses(id) on delete cascade,
  type text not null,
  in_app boolean not null default true,
  sound boolean not null default true,
  email boolean not null default false,
  telegram boolean not null default false,
  unique (business_id, type)
);

create table if not exists bot_health (
  business_id uuid primary key references businesses(id) on delete cascade,
  token_ok boolean,
  subscribed boolean,
  last_checked_at timestamptz,
  last_error text,
  last_customer_message_at timestamptz
);

create table if not exists business_users (
  id bigint generated by default as identity primary key,
  business_id uuid not null references businesses(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'staff' check (role in ('owner','manager','staff')),
  created_at timestamptz not null default now(),
  unique (business_id, user_id)
);

create table if not exists audit_log (
  id bigint generated by default as identity primary key,
  business_id uuid not null references businesses(id) on delete cascade,
  user_id uuid,
  action text not null,
  table_name text,
  record_id text,
  old_data jsonb,
  new_data jsonb,
  created_at timestamptz not null default now()
);
create index if not exists audit_log_biz_idx on audit_log (business_id, created_at desc);

